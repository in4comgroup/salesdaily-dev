// Compile only AI tooling into a private temporary directory. This avoids
// native tsx/esbuild dependencies when node_modules came from another OS.
import { spawnSync } from "node:child_process"
import { mkdtempSync, rmSync } from "node:fs"
import { tmpdir } from "node:os"
import path from "node:path"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"

const require = createRequire(import.meta.url)

const [command, ...args] = process.argv.slice(2)
if (!["check", "test", "seed"].includes(command)) {
  console.error("Usage: node tools/ai/run.mjs check --config path [--probe task] [--model id] [--debug] | test | seed --input file [--comment text] [--replace] [--dry-run]")
  process.exitCode = 1
} else {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
  const output = mkdtempSync(path.join(tmpdir(), "crm-ai-check-"))
  try {
    const compilation = spawnSync(process.execPath, [
      "--max-old-space-size=2048", require.resolve("typescript/bin/tsc"),
      "--target", "es2022", "--module", "commonjs", "--moduleResolution", "node",
      "--skipLibCheck", "--strict", "--esModuleInterop", "--rootDir", root,
      "--outDir", output, "--pretty", "false",
      "src/server/ai/index.ts", "tools/ai/check.ts", "tools/ai/runtime.test.ts", "tools/ai/seed.ts",
    ], { cwd: root, stdio: "inherit" })
    if (compilation.error || compilation.status !== 0) {
      console.error("AI tooling compilation failed")
      process.exitCode = compilation.status || 1
    } else {
      const result = spawnSync(process.execPath, [
        "--conditions=react-server",
        path.join(output, "tools/ai", { test: "runtime.test.js", seed: "seed.js", check: "check.js" }[command]),
        ...args,
      ], {
        cwd: root,
        stdio: "inherit",
        env: {
          ...process.env,
          NODE_PATH: [
            path.join(root, "node_modules"),
            path.join(path.dirname(require.resolve("next/package.json")), "dist/compiled"),
            process.env.NODE_PATH,
          ].filter(Boolean).join(path.delimiter),
        },
      })
      if (result.error) console.error("Cannot start AI tooling")
      process.exitCode = result.status ?? 1
    }
  } catch {
    console.error("Cannot prepare AI tooling; check installed project dependencies")
    process.exitCode = 1
  } finally {
    // Only the directory generated by this invocation is removed.
    rmSync(output, { recursive: true, force: true })
  }
}
